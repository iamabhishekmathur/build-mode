import { createRng, fakeUuid, type Json, type JsonObject } from '@stagecraft/core';
import { genValue, IDENT, literal, resolve, singular, tsDeclaration, type GenContext } from './model.ts';
import type { ApiPlan, Collection, Plan } from './plan.ts';

export interface EmitOptions {
  seed: number;
  /** Rows per top-level collection. */
  count: number;
  /** Header line: where the files came from and how to regenerate them. */
  source: string;
  command: string;
}

export const MARKER = '// Generated by `stagecraft mocks generate`';

const header = (o: EmitOptions, what: string) =>
  `${MARKER} from ${o.source}. Do not edit: the next run overwrites this file.
// Regenerate: ${o.command}
// ${what}
`;

const prop = (k: string) => (IDENT.test(k) ? `.${k}` : `[${JSON.stringify(k)}]`);
const key = (k: string) => (IDENT.test(k) ? k : JSON.stringify(k));
const str = (s: string) => JSON.stringify(s);

function idValue(c: Collection, i: number, rng: ReturnType<typeof createRng>): Json {
  if (c.idKind === 'int') return i + 1;
  if (c.idKind === 'uuid') return fakeUuid(rng);
  return `${c.idPrefix}_${String(i + 1).padStart(3, '0')}`;
}

/** Rows per collection: nested collections get more, spread over their parents. */
export const rowCount = (c: Collection, count: number) => (c.parent ? Math.max(count, Math.min(count * 2, 16)) : count);

/** Build the seed data. Same plan + seed → identical data. */
export function buildSeed(p: ApiPlan, o: EmitOptions): Record<string, Json> {
  const rng = createRng(o.seed);
  const ids = new Map<Collection, Json[]>();
  const counts = new Map<Collection, number>();
  for (const c of p.collections) {
    const n = rowCount(c, o.count);
    counts.set(c, n);
    ids.set(c, Array.from({ length: n }, (_, i) => idValue(c, i, rng)));
  }
  const foreignKeys = new Map<string, Json[]>();
  for (const c of p.collections) {
    foreignKeys.set(singular(c.key).toLowerCase(), ids.get(c)!);
    foreignKeys.set(singular(c.typeName).toLowerCase(), ids.get(c)!);
  }
  const ctx = (index: number): GenContext => ({ rng, types: p.types, index, depth: 0, stack: [], foreignKeys });
  const db: Record<string, Json> = {};
  for (const c of p.collections) {
    const rows: JsonObject[] = [];
    const parentIds = c.parent ? ids.get(c.parent.coll)! : [];
    for (let i = 0; i < counts.get(c)!; i++) {
      const row = genValue({ kind: 'ref', name: c.typeName }, singular(c.key), ctx(i)) as JsonObject;
      const out: JsonObject = { [c.idField]: ids.get(c)![i]!, ...row };
      out[c.idField] = ids.get(c)![i]!;
      if (c.parent) out[c.parent.fk] = parentIds[i % parentIds.length]!;
      rows.push(out);
    }
    db[c.key] = rows;
  }
  for (const s of p.singletons) db[s.key] = genValue({ kind: 'ref', name: s.typeName }, s.key, ctx(0));
  return db;
}

export function emitTypes(p: ApiPlan, o: EmitOptions): string {
  const decls = [...p.types].map(([n, s]) => tsDeclaration(n, s));
  const rowType = (c: Collection) => (c.added.length ? `(${c.typeName} & { ${c.added.map((a) => `${key(a.name)}: ${a.ts}`).join('; ')} })` : c.typeName);
  const db = [
    ...p.collections.map((c) => `  ${key(c.key)}: ${rowType(c)}[];`),
    ...p.singletons.map((s) => `  ${key(s.key)}: ${s.typeName};`),
  ];
  return `${header(o, 'API types, and the shape of the generated mock DB.')}
${decls.join('\n\n')}

/** The part of the mock DB that the generated handlers read and write. */
export interface GeneratedDB {
${db.join('\n')}
}
`;
}

export function emitSeed(p: ApiPlan, o: EmitOptions): string {
  const db = buildSeed(p, o);
  return `${header(o, 'Fake, deterministic seed data. Spread it into stagecraft/seed.ts and override what you need.')}import type { GeneratedDB } from './types';

export const generatedSeed = (): GeneratedDB => (${literal(db as Json)});
`;
}

export function emitStates(p: ApiPlan, o: EmitOptions): string {
  const entries = p.collections.map((c) => {
    const id = c.idKind === 'int' ? 'i + 1' : c.idKind === 'uuid' ? '`00000000-0000-4000-8000-${String(i + 1).padStart(12, \'0\')}`' : `\`${c.idPrefix}_\${String(i + 1).padStart(3, '0')}\``;
    const opts = [`baseline: seed${prop(c.key)}`, `idField: ${str(c.idField)}`, ...(c.textFields.length ? [`textFields: ${JSON.stringify(c.textFields)}`] : [])];
    return `  ...edgeStates(${str(c.key)}, (i) => ({ ...cycle(seed${prop(c.key)}, i), ${key(c.idField)}: ${id} }), { ${opts.join(', ')} }),`;
  });
  return `${header(o, 'Edge presets per collection: empty, one, many (1,200 rows), long text, right-to-left, unicode.')}import { defineStates, edgeStates } from '@stagecraft/core';
import { generatedSeed } from './seed';

const seed = generatedSeed();
const cycle = <T>(rows: T[], i: number): T => rows[i % rows.length] as T;

export const generatedStates = defineStates({
${entries.join('\n')}
});
`;
}

const PRELUDE = `import { defineHandlers } from '@stagecraft/core';
import type { GeneratedDB } from './types';

/** One record of a generated collection. */
export type Row<K extends keyof GeneratedDB> = GeneratedDB[K] extends readonly (infer T)[] ? T : never;

/** Ids from the URL are strings; ids in the DB may be numbers. */
export const sameId = (a: unknown, b: string | undefined) => b !== undefined && String(a) === b;

export const now = () => new Date().toISOString();

/** \`?limit\` / \`?page\` / \`?offset\` paging over an array. */
export function paginate<T>(items: T[], query: Record<string, string>, p: { limit?: string; page?: string; offset?: string; defaultLimit?: number }) {
  const rawLimit = p.limit ? Number(query[p.limit]) : NaN;
  const limit = Number.isFinite(rawLimit) && rawLimit >= 0 ? rawLimit : (p.defaultLimit ?? items.length);
  let start = 0;
  if (p.offset && query[p.offset] !== undefined) start = Math.max(0, Number(query[p.offset]) || 0);
  else if (p.page && query[p.page] !== undefined) start = (Math.max(1, Number(query[p.page]) || 1) - 1) * limit;
  const page = items.slice(start, start + limit);
  return { items: page, total: items.length, limit, start, page: limit ? Math.floor(start / limit) + 1 : 1, hasMore: start + page.length < items.length };
}

/** A new id that does not collide with existing ones. */
export function nextId(existing: unknown[], kind: 'int' | 'uuid' | 'string', prefix: string): any {
  if (kind === 'int') return existing.reduce<number>((m, v) => Math.max(m, Number(v) || 0), 0) + 1;
  if (kind === 'uuid') return crypto.randomUUID();
  const taken = new Set(existing.map(String));
  for (let n = existing.length + 1; ; n++) {
    const id = \`\${prefix}_\${String(n).padStart(3, '0')}\`;
    if (!taken.has(id)) return id;
  }
}
`;

function metaValue(name: string, nullable: boolean | undefined): string | undefined {
  const n = name.toLowerCase().replace(/_/g, '');
  if (/^(total|totalcount|count|totalitems|totalresults)$/.test(n)) return 'page.total';
  if (/^(hasmore|hasnext|hasnextpage|more)$/.test(n)) return 'page.hasMore';
  if (/^(page|pagenumber|currentpage)$/.test(n)) return 'page.page';
  if (/^(limit|perpage|pagesize|size)$/.test(n)) return 'page.limit';
  if (/^(offset|skip|start)$/.test(n)) return 'page.start';
  if (/^(totalpages|pages|pagecount)$/.test(n)) return 'Math.max(1, Math.ceil(page.total / (page.limit || 1)))';
  if (/(cursor|next|nexttoken|nextpagetoken|nextpage|after)$/.test(n)) return nullable ? 'null' : 'page.hasMore ? String(page.start + page.limit) : ""';
  return undefined;
}

function handlerBody(h: Plan, p: ApiPlan, sample: (s: Plan) => Json): string[] {
  const L: string[] = [];
  const nf = (what: string) => `return ctx.reply(404, { error: ${str(`${what} not found`)} });`;
  const find = (c: Collection, param: string, parentParam?: string) => {
    const conds = [`sameId(x${prop(c.idField)}, ctx.params${prop(param)})`];
    if (c.parent && parentParam) conds.push(`sameId(x${prop(c.parent.fk)}, ctx.params${prop(parentParam)})`);
    return `(x) => ${conds.join(' && ')}`;
  };
  const parentCheck = (c: Collection, parentParam?: string) => {
    if (!c.parent || !parentParam) return;
    const pc = c.parent.coll;
    L.push(`if (!ctx.db${prop(pc.key)}.some((x) => sameId(x${prop(pc.idField)}, ctx.params${prop(parentParam)}))) ${nf(pc.typeName)}`);
  };
  const out = (expr: string, status: number, wrapProp?: string) => {
    const v = wrapProp ? `{ ${key(wrapProp)}: ${expr} }` : expr;
    L.push(status === 200 ? `return ${v};` : `return ctx.reply(${status}, ${v});`);
  };
  const status = h.op.status >= 200 && h.op.status < 300 ? h.op.status : 200;
  const stringProp = (c: { props: { name: string; shape: any }[] }, name: string) => c.props.some((x) => x.name === name && resolve(x.shape, p.types).kind === 'string');
  switch (h.kind) {
    case 'list': {
      const c = h.coll;
      parentCheck(c, h.parentParam);
      const base = `ctx.db${prop(c.key)}`;
      const decl = h.filters.length ? 'let' : 'const';
      L.push(c.parent && h.parentParam ? `${decl} items = ${base}.filter((x) => sameId(x${prop(c.parent.fk)}, ctx.params${prop(h.parentParam)}));` : `${decl} items = ${base};`);
      for (const f of h.filters) L.push(`if (ctx.query${prop(f)} !== undefined) items = items.filter((x) => String(x${prop(f)}) === ctx.query${prop(f)});`);
      const pg = h.paging;
      const hasPaging = pg.limit || pg.page || pg.offset;
      if (hasPaging || h.wrapper) {
        const opts = [pg.limit && `limit: ${str(pg.limit)}`, pg.page && `page: ${str(pg.page)}`, pg.offset && `offset: ${str(pg.offset)}`, pg.defaultLimit !== undefined && `defaultLimit: ${pg.defaultLimit}`].filter(Boolean);
        L.push(`const page = paginate(items, ctx.query, ${opts.length ? `{ ${opts.join(', ')} }` : '{}'});`);
      }
      if (h.wrapper) {
        const fields = [`${key(h.wrapper.prop)}: page.items`];
        for (const m of h.wrapper.meta) {
          const v = metaValue(m.name, resolve(m.shape, p.types).nullable || m.shape.nullable);
          if (v) fields.push(`${key(m.name)}: ${v}`);
          else if (m.required) fields.push(`${key(m.name)}: ${literal(sample({ kind: 'static', op: h.op, shape: m.shape }), '      ')}`);
        }
        L.push(`return { ${fields.join(', ')} };`);
      } else L.push(hasPaging ? 'return page.items;' : 'return items;');
      break;
    }
    case 'get': {
      L.push(`const item = ctx.db${prop(h.coll.key)}.find(${find(h.coll, h.param, h.parentParam)});`);
      L.push(`if (!item) ${nf(h.coll.typeName)}`);
      out('item', status, h.wrapProp);
      break;
    }
    case 'update': {
      const c = h.coll;
      L.push(`const item = ctx.db${prop(c.key)}.find(${find(c, h.param, h.parentParam)});`);
      L.push(`if (!item) ${nf(c.typeName)}`);
      const keep = [`${key(c.idField)}: item${prop(c.idField)}`, ...(c.parent ? [`${key(c.parent.fk)}: item${prop(c.parent.fk)}`] : [])];
      L.push(`Object.assign(item, ctx.body ?? {}, { ${keep.join(', ')} });`);
      if (stringProp(c, 'updatedAt')) L.push('item.updatedAt = now();');
      out('item', status === 201 ? 200 : status, h.wrapProp);
      break;
    }
    case 'delete': {
      const c = h.coll;
      L.push(`const index = ctx.db${prop(c.key)}.findIndex(${find(c, h.param, h.parentParam)});`);
      L.push(`if (index < 0) ${nf(c.typeName)}`);
      const children = p.collections.filter((x) => x.parent?.coll === c);
      L.push(children.length || h.op.hasBody ? `const removed = ctx.db${prop(c.key)}.splice(index, 1)[0]!;` : `ctx.db${prop(c.key)}.splice(index, 1);`);
      for (const child of children) {
        L.push(`ctx.db${prop(child.key)} = ctx.db${prop(child.key)}.filter((x) => !sameId(x${prop(child.parent!.fk)}, String(removed${prop(c.idField)})));`);
      }
      if (h.op.hasBody) out('removed', status, h.wrapProp);
      else L.push(`return ctx.reply(${status === 200 ? 204 : status});`);
      break;
    }
    case 'create': {
      const c = h.coll;
      parentCheck(c, h.parentParam);
      const fields = ['...NEW', '...(ctx.body ?? {})', `${key(c.idField)}: nextId(ctx.db${prop(c.key)}.map((x) => x${prop(c.idField)}), ${str(c.idKind)}, ${str(c.idPrefix)})`];
      if (c.parent && h.parentParam) fields.push(`${key(c.parent.fk)}: ${c.parent.coll.idKind === 'int' ? `Number(ctx.params${prop(h.parentParam)})` : `ctx.params${prop(h.parentParam)}`}`);
      for (const f of ['createdAt', 'updatedAt']) if (stringProp(c, f)) fields.push(`${f}: now()`);
      L.push(`const NEW = ${literal(sample({ kind: 'static', op: h.op, shape: { kind: 'ref', name: c.typeName } }), '    ')};`);
      L.push(`const item = { ${fields.join(', ')} } as Row<${str(c.key)}>;`);
      L.push(`ctx.db${prop(c.key)}.push(item);`);
      out('item', status, h.wrapProp);
      break;
    }
    case 'action': {
      const c = h.coll;
      L.push(`const item = ctx.db${prop(c.key)}.find(${find(c, h.param, h.parentParam)});`);
      L.push(`if (!item) ${nf(c.typeName)}`);
      if (h.status) L.push(`item${prop(c.props.some((x) => x.name === 'status') ? 'status' : 'state')} = ${str(h.status)};`);
      if (stringProp(c, 'updatedAt')) L.push('item.updatedAt = now();');
      if ('sample' in h) L.push(`return ${literal(sample(h), '    ')};`);
      else out('item', status, undefined);
      break;
    }
    case 'singleton-get':
      L.push(`return ctx.db${prop(h.single.key)};`);
      break;
    case 'singleton-update':
      L.push(`Object.assign(ctx.db${prop(h.single.key)}, ctx.body ?? {});`);
      if (stringProp(h.single, 'updatedAt')) L.push(`ctx.db${prop(h.single.key)}.updatedAt = now();`);
      L.push(`return ctx.db${prop(h.single.key)};`);
      break;
    case 'singleton-action':
      if (h.status) L.push(`ctx.db${prop(h.single.key)}${prop(h.single.props.some((x) => x.name === 'status') ? 'status' : 'state')} = ${str(h.status)};`);
      if ('sample' in h) L.push(`return ${literal(sample(h), '    ')};`);
      else L.push(`return ctx.db${prop(h.single.key)};`);
      break;
    case 'static':
      if (!h.op.hasBody) L.push(`return ctx.reply(${status === 200 ? 204 : status});`);
      else if (!h.shape) L.push(status === 200 ? 'return { ok: true };' : `return ctx.reply(${status}, { ok: true });`);
      else {
        const v = literal(sample(h), '    ');
        L.push(status === 200 ? `return ${v};` : `return ctx.reply(${status}, ${v});`);
      }
      break;
  }
  return L;
}

export function emitHandlers(p: ApiPlan, o: EmitOptions): string {
  const rng = createRng(o.seed + 7919);
  const sample = (h: Plan): Json => {
    const shape = h.kind === 'static' ? h.shape : h.op.response;
    if (!shape) return null;
    return genValue(shape, 'value', { rng, types: p.types, index: 0, depth: 0, stack: [], foreignKeys: new Map() });
  };
  const seen = new Set<string>();
  const entries: string[] = [];
  for (const h of p.handlers) {
    const k = `${h.op.method} ${h.op.route}`;
    if (seen.has(k)) continue;
    seen.add(k);
    const body = handlerBody(h, p, sample);
    const doc = h.op.operationId ? `  // ${h.op.operationId} (${h.kind})\n` : `  // ${h.kind}\n`;
    entries.push(`${doc}  ${str(k)}: (ctx) => {\n${body.map((l) => `    ${l}`).join('\n')}\n  },`);
  }
  return `${header(o, 'Mock handlers for every operation in the spec. Spread them into stagecraft/mocks.ts; your own keys after the spread win.')}${PRELUDE}
export const generatedHandlers = defineHandlers<GeneratedDB>({
${entries.join('\n')}
});
`;
}

export function emitIndex(o: EmitOptions): string {
  return `${header(o, 'Entry point.')}export { generatedSeed } from './seed';
export { generatedHandlers } from './handlers';
export { generatedStates } from './states';
export type * from './types';
`;
}
