import { existsSync, mkdirSync, readFileSync, writeFileSync } from 'node:fs';
import { isAbsolute, join, relative, resolve } from 'node:path';
import { emitHandlers, emitIndex, emitSeed, emitStates, emitTypes, MARKER, rowCount, type EmitOptions } from './emit.ts';
import { readOpenApiSource, type ApiSource } from './openapi.ts';
import { plan } from './plan.ts';
import { parseTypeMapping, readTsSource, type TypeMapping } from './ts-source.ts';

export { parseTypeMapping, type TypeMapping } from './ts-source.ts';

export interface GenerateOptions {
  /** Folder that relative paths resolve against (the repo root). */
  cwd: string;
  /** OpenAPI 3.x spec (JSON or YAML). */
  openapi?: string;
  /** TypeScript file with exported API types, plus which type serves which path. */
  types?: string;
  typeMap?: (TypeMapping | string)[];
  /** Output folder. Default `stagecraft/generated`. */
  out?: string;
  /** PRNG seed. Same seed → identical files. Default 42. */
  seed?: number;
  /** Rows per collection. Default 8. */
  count?: number;
  /** Overwrite files in the output folder that were not generated by Stagecraft. */
  force?: boolean;
}

export interface GenerateResult {
  outDir: string;
  files: string[];
  collections: { key: string; type: string; rows: number; edgeStates: string[] }[];
  singletons: { key: string; type: string }[];
  endpoints: { endpoint: string; kind: string }[];
  /** How to wire the output into stagecraft/{seed,mocks,states}.ts. */
  snippet: string;
}

const FILES = ['types.ts', 'seed.ts', 'handlers.ts', 'states.ts', 'index.ts'] as const;

const posix = (p: string) => p.split('\\').join('/');

export const WIRING_SNIPPET = (outRel: string) => {
  const rel = `./${posix(relative('stagecraft', outRel)) || '.'}`.replace(/^\.\/\.\.\//, '../');
  return `// stagecraft/seed.ts
import { generatedSeed } from '${rel}/seed';
export const seed = () => ({
  ...generatedSeed(),
  // your own records and overrides here
});
export type DB = ReturnType<typeof seed>;

// stagecraft/mocks.ts
import { defineHandlers } from '@stagecraft/core';
import { generatedHandlers } from '${rel}/handlers';
import type { DB } from './seed';
export const handlers = defineHandlers<DB>({
  ...generatedHandlers,
  // hand-written handlers after the spread win, e.g. 'GET /v1/me': ({ db, persona }) => ...
});

// stagecraft/states.ts
import { defineStates } from '@stagecraft/core';
import { generatedStates } from '${rel}/states';
export const states = defineStates({
  ...generatedStates,
  // your own entities after the spread win
});`;
};

/** Generate typed seed data, mock handlers, edge-state presets and types from an API description. */
export async function generateMocks(o: GenerateOptions): Promise<GenerateResult> {
  const abs = (p: string) => (isAbsolute(p) ? p : resolve(o.cwd, p));
  const seed = o.seed ?? 42;
  const count = Math.max(1, Math.min(o.count ?? 8, 200));
  const outRel = o.out ?? 'stagecraft/generated';
  const outDir = abs(outRel);
  let src: ApiSource;
  let source: string;
  let args: string;
  if (o.openapi) {
    src = readOpenApiSource(abs(o.openapi));
    source = posix(relative(o.cwd, abs(o.openapi)));
    args = `--openapi ${source}`;
  } else if (o.types) {
    const maps = (o.typeMap ?? []).map((m) => (typeof m === 'string' ? parseTypeMapping(m) : m));
    if (!maps.length) throw new Error('--types needs at least one --type Name:/path mapping, e.g. --type Invoice:/v1/invoices');
    src = await readTsSource(abs(o.types), maps);
    source = posix(relative(o.cwd, abs(o.types)));
    args = `--types ${source} ${maps.map((m) => `--type ${m.type}${m.collection === true ? '[]' : m.collection === false ? '!' : ''}:${m.path}`).join(' ')}`;
  } else throw new Error('Give an API description: --openapi <spec.json|yaml> or --types <file.ts> --type Name:/path');
  const outArg = posix(relative(o.cwd, outDir));
  const emit: EmitOptions = {
    seed,
    count,
    source,
    command: `npx --no stagecraft mocks generate ${args}${outArg !== 'stagecraft/generated' ? ` --out ${outArg}` : ''} --seed ${seed}${count !== 8 ? ` --count ${count}` : ''}`,
  };
  const p = plan(src);
  if (!p.handlers.length) throw new Error(`${source} has no operations`);
  const contents: Record<(typeof FILES)[number], string> = {
    'types.ts': emitTypes(p, emit),
    'seed.ts': emitSeed(p, emit),
    'handlers.ts': emitHandlers(p, emit),
    'states.ts': emitStates(p, emit),
    'index.ts': emitIndex(emit),
  };
  // Never overwrite a file a person wrote.
  for (const f of FILES) {
    const file = join(outDir, f);
    if (!o.force && existsSync(file) && !readFileSync(file, 'utf8').startsWith(MARKER)) {
      throw new Error(`${posix(relative(o.cwd, file))} was not generated by Stagecraft. Move it, choose another --out, or pass --force.`);
    }
  }
  mkdirSync(outDir, { recursive: true });
  const files: string[] = [];
  for (const f of FILES) {
    const file = join(outDir, f);
    if (!existsSync(file) || readFileSync(file, 'utf8') !== contents[f]) writeFileSync(file, contents[f]);
    files.push(posix(relative(o.cwd, file)));
  }
  return {
    outDir,
    files,
    collections: p.collections.map((c) => ({ key: c.key, type: c.typeName, rows: rowCount(c, count), edgeStates: ['seeded', 'empty', 'one', 'many', 'long-text', 'rtl', 'unicode'] })),
    singletons: p.singletons.map((s) => ({ key: s.key, type: s.typeName })),
    endpoints: [...new Map(p.handlers.map((h) => [`${h.op.method} ${h.op.route}`, h.kind])).entries()].map(([endpoint, kind]) => ({ endpoint, kind })),
    snippet: WIRING_SNIPPET(outArg),
  };
}

const USAGE = `Usage:
  stagecraft mocks generate --openapi <spec.json|yaml> [--out stagecraft/generated] [--seed 42] [--count 8] [--force]
  stagecraft mocks generate --types <file.ts> --type Name:/path [--type Name:/path ...] [--out ...] [--seed 42]
      --type Invoice:/v1/invoices    plural path → collection (list, get, create, update, delete)
      --type Account:/v1/account     singular path → singleton (get, update)
      Add [] (Invoice[]:/v1/stock) to force a collection, ! (Me!:/v1/people) to force a singleton.`;

export async function mocksCommand(cwd: string, sub: string | undefined, rest: string[], log: (m: string) => void): Promise<number> {
  if (sub !== 'generate') {
    log(USAGE);
    return sub ? 1 : 0;
  }
  const val = (name: string) => {
    const i = rest.indexOf(name);
    return i === -1 ? undefined : rest[i + 1];
  };
  const all = (name: string) => rest.flatMap((a, i) => (a === name && rest[i + 1] ? [rest[i + 1]!] : []));
  const num = (name: string) => {
    const v = val(name);
    if (v === undefined) return undefined;
    if (!/^\d+$/.test(v)) throw new Error(`${name} must be a whole number`);
    return Number(v);
  };
  const r = await generateMocks({
    cwd,
    openapi: val('--openapi'),
    types: val('--types'),
    typeMap: all('--type'),
    out: val('--out'),
    seed: num('--seed'),
    count: num('--count'),
    force: rest.includes('--force'),
  });
  for (const f of r.files) log(`wrote ${f}`);
  log('');
  for (const c of r.collections) log(`collection ${c.key} (${c.type}, ${c.rows} rows) + edge states: ${c.edgeStates.join(', ')}`);
  for (const s of r.singletons) log(`singleton  ${s.key} (${s.type})`);
  log(`${r.endpoints.length} handlers: ${r.endpoints.map((e) => e.endpoint).join(', ')}`);
  log(`\nWire it in (spread first; your own keys after the spread win):\n\n${r.snippet}\n`);
  return 0;
}
