describe('mocks generate from TypeScript API types (FR-502)', () => {
  it('reads exported interfaces and type aliases and generates CRUD for a collection and a singleton', async () => {
    const root = tmpRoot('gen-ts');
    mkdirSync(join(root, 'src'), { recursive: true });
    writeFileSync(
      join(root, 'src/api.ts'),
      `export type InvoiceStatus = 'draft' | 'open' | 'paid';
export interface Money { amount: number; currency: 'USD' | 'EUR' }
export interface Invoice {
  id: string;
  customerName: string;
  status: InvoiceStatus;
  total: Money;
  issuedAt: Date;
  notes?: string | null;
  tags: string[];
  archived: boolean;
}
export type Account = { id: string; name: string; plan: 'free' | 'pro'; seats: number };
interface Internal { secret: string }
export type Unused = Internal;
`,
    );
    const r = spawnSync(process.execPath, [BIN, 'mocks', 'generate', '--types', 'src/api.ts', '--type', 'Invoice:/api/invoices', '--type', 'Account:/api/account', '--seed', '3'], { cwd: root, encoding: 'utf8' });
    expect(r.stderr).toBe('');
    expect(r.status).toBe(0);
    const types = readFileSync(join(root, 'stagecraft/generated/types.ts'), 'utf8');
    expect(types).toMatch(/export interface Invoice \{[\s\S]*status: InvoiceStatus;[\s\S]*total: Money;[\s\S]*notes\?: string \| null;[\s\S]*archived: boolean;/);
    expect(types).toContain('export type InvoiceStatus = "draft" | "open" | "paid";');
    expect(readFileSync(join(root, 'stagecraft/generated/handlers.ts'), 'utf8')).toMatch(/--types src\/api\.ts --type Invoice:\/api\/invoices --type Account:\/api\/account --seed 3/);
    const result = await generateMocks({ cwd: root, types: 'src/api.ts', typeMap: ['Invoice:/api/invoices', 'Account:/api/account'], seed: 3 });
    const config = wire(root, result, '/api');
    typecheck(root);
    const { url } = await serve(config);
    const api = async (method: string, path: string, body?: unknown) => {
      const res = await fetch(url + path, { method, headers: { 'content-type': 'application/json' }, body: body ? JSON.stringify(body) : undefined });
      const text = await res.text();
      return { status: res.status, body: text ? JSON.parse(text) : undefined };
    };
    const list = (await api('GET', '/api/invoices')).body;
    expect(list).toHaveLength(8);
    expect(['draft', 'open', 'paid']).toContain(list[0].status);
    expect(list[0].issuedAt).toMatch(/^\d{4}-\d{2}-\d{2}T/);
    expect((await api('GET', '/api/invoices?limit=2&offset=1')).body.map((i: any) => i.id)).toEqual(list.slice(1, 3).map((i: any) => i.id));
    const created = await api('POST', '/api/invoices', { customerName: 'Hooli' });
    expect(created.status).toBe(201);
    expect((await api('PATCH', `/api/invoices/${created.body.id}`, { status: 'paid' })).body.status).toBe('paid');
    expect((await api('DELETE', `/api/invoices/${created.body.id}`)).status).toBe(204);
    expect((await api('GET', `/api/invoices/${created.body.id}`)).status).toBe(404);
    expect((await api('GET', '/api/account')).body).toMatchObject({ plan: expect.stringMatching(/^(free|pro)$/) });
    expect((await api('PATCH', '/api/account', { seats: 12 })).body.seats).toBe(12);
  });

  it('explains a missing type', async () => {
    const root = tmpRoot('gen-ts-missing');
    mkdirSync(join(root, 'src'));
    writeFileSync(join(root, 'src/api.ts'), 'export interface Thing { id: string }\n');
    await expect(generateMocks({ cwd: root, types: 'src/api.ts', typeMap: ['Nope:/api/nopes'] })).rejects.toThrow(/does not export a type "Nope". Exported: Thing/);
  });
});

describe('edge presets library (FR-506)', () => {
  it('is deterministic and gives each preset its shape', () => {
    const a = createRng(5);
    const b = createRng(5);
    expect(Array.from({ length: 5 }, () => a.next())).toEqual(Array.from({ length: 5 }, () => b.next()));
    const cat = edgeStates('payments', (i, r) => ({ id: `p${i}`, vendor: 'Globex', amount: r.int(1, 99) }), { many: 1500 });
    const st = cat.payments!.states;
    const rows = (name: string) => ((st[name]!.db as any).payments.$set as any[]);
    expect(cat.payments!.default).toBe('seeded');
    expect(rows('empty')).toEqual([]);
    expect(rows('one')).toHaveLength(1);
    expect(rows('many')).toHaveLength(1500);
    expect(rows('long-text')[0].vendor).toBe(EDGE_TEXT.long);
    expect(rows('rtl').map((r) => r.vendor)).toEqual(expect.arrayContaining([EDGE_TEXT.rtl[0]]));
    expect(rows('unicode')[0].vendor).toBe(EDGE_TEXT.unicode[0]);
    expect(rows('rtl')[0].id).toBe('p0'); // ids and numbers are left alone
  });
});
